#!/usr/bin/env python3
"""Convert Tanzil files into per-Surah JSON + lazy loader index for React Native.

Usage:
  python tools/convert_quran.py --arabic tools/source/quran-uthmani.txt \
     --translation tools/source/translation.txt --meta tools/source/quran-data.js \
     --out src/data/quran

Quran letters are never changed. Only a leading Bismillah attached to Ayah 1
(Surahs 2-114 except 9) is moved to the header flag, if present in the source.
"""
import argparse, json, re, sys
from pathlib import Path


def read_pipe_file(path):
    data = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("|", 2)
        if len(parts) != 3:
            continue
        s, a, t = parts
        data[(int(s), int(a))] = t.strip()
    return data


ROW = re.compile(
    r"\[\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*"
    r"['\"](.+?)['\"]\s*,\s*['\"](.+?)['\"]\s*,\s*['\"](.+?)['\"]\s*,\s*['\"](\w+)['\"]\s*\]"
)


def read_meta(path):
    text = Path(path).read_text(encoding="utf-8")
    rows = ROW.findall(text)
    if len(rows) != 114:
        sys.exit(f"ERROR: expected 114 surah rows in meta file, found {len(rows)}. "
                 "Check the quran-data.js format.")
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arabic", required=True)
    ap.add_argument("--translation", required=True)
    ap.add_argument("--meta", required=True)
    ap.add_argument("--out", default="src/data/quran")
    args = ap.parse_args()

    ar = read_pipe_file(args.arabic)
    tr = read_pipe_file(args.translation)
    suras = read_meta(args.meta)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    bismillah = ar[(1, 1)]
    index, total, stripped, problems = [], 0, 0, 0

    for i, (_start, ayas, _order, _rukus, name_ar, name_tr, name_en, typ) in enumerate(suras, 1):
        ayahs = []
        for a in range(1, int(ayas) + 1):
            if (i, a) not in ar or (i, a) not in tr:
                print(f"MISSING: surah {i} ayah {a}")
                problems += 1
                continue
            text = ar[(i, a)]
            if a == 1 and i not in (1, 9) and text.startswith(bismillah) and len(text) > len(bismillah):
                text = text[len(bismillah):].strip()
                stripped += 1
            if not text or not tr[(i, a)]:
                print(f"EMPTY: surah {i} ayah {a}")
                problems += 1
            ayahs.append({"n": a, "ar": text, "tr": tr[(i, a)]})
        header = i not in (1, 9)
        (out / f"surah_{i:03d}.json").write_text(
            json.dumps({"number": i, "bismillahHeader": header, "ayahs": ayahs}, ensure_ascii=False),
            encoding="utf-8")
        index.append({
            "number": i, "nameArabic": name_ar, "nameEnglish": name_en,
            "nameTransliteration": name_tr, "ayahCount": int(ayas),
            "type": "Makki" if typ.lower().startswith("mec") else "Madani",
            "bismillahHeader": header})
        total += len(ayahs)

    (out / "surahs.json").write_text(json.dumps(index, ensure_ascii=False), encoding="utf-8")

    lines = ["// GENERATED by tools/convert_quran.py — do not edit by hand",
             "import type { SurahContent } from '../../types/quran';", "",
             "export const surahLoaders: Record<number, () => SurahContent> = {"]
    for i in range(1, 115):
        lines.append(f"  {i}: () => require('./surah_{i:03d}.json') as SurahContent,")
    lines.append("};")
    (out / "index.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Surahs: {len(index)} | Total ayahs: {total} (expected 6236) | "
          f"Bismillah moved from ayah 1: {stripped} (expected 0 or 112) | problems: {problems}")
    if total != 6236 or problems:
        print("WARNING: validation failed — do NOT use this data until fixed.")
        sys.exit(1)


if __name__ == "__main__":
    main()
