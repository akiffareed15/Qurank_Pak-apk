// tools/convert_quran.js
// Equivalent to convert_quran.py for Node.js environment
const fs = require('fs');
const path = require('path');

function readPipeFile(filePath) {
  const content = fs.readFileSync(filePath, 'utf-8');
  const lines = content.split(/\r?\n/);
  const data = new Map();

  for (let line of lines) {
    line = line.trim();
    if (!line || line.startsWith('#')) continue;
    const parts = line.split('|');
    if (parts.length < 3) continue;
    const s = parseInt(parts[0], 10);
    const a = parseInt(parts[1], 10);
    const t = parts.slice(2).join('|').trim();
    data.set(`${s},${a}`, t);
  }
  return data;
}

const ROW_REGEX = /\[\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*['"](.+?)['"]\s*,\s*['"](.+?)['"]\s*,\s*['"](.+?)['"]\s*,\s*['"](\w+)['"]\s*\]/g;

function readMeta(filePath) {
  const text = fs.readFileSync(filePath, 'utf-8');
  const rows = [];
  let match;
  while ((match = ROW_REGEX.exec(text)) !== null) {
    rows.push({
      start: parseInt(match[1], 10),
      ayas: parseInt(match[2], 10),
      order: parseInt(match[3], 10),
      rukus: parseInt(match[4], 10),
      name_ar: match[5],
      name_tr: match[6],
      name_en: match[7],
      typ: match[8],
    });
  }
  if (rows.length !== 114) {
    console.error(`ERROR: expected 114 surah rows in meta file, found ${rows.length}.`);
    process.exit(1);
  }
  return rows;
}

function main() {
  const arabicFile = path.resolve(__dirname, '../Quran/quran-uthmani.txt');
  const translationFile = path.resolve(__dirname, 'source/translation.txt');
  const metaFile = path.resolve(__dirname, 'source/quran-data.js');
  const outDir = path.resolve(__dirname, '../src/data/quran');

  fs.mkdirSync(outDir, { recursive: true });

  const ar = readPipeFile(arabicFile);
  const tr = readPipeFile(translationFile);
  const suras = readMeta(metaFile);

  const bismillahRegex = /^ب[\u0651\u0650]*سْمِ\s+ٱللَّهِ\s+ٱلرَّحْمَـٰنِ\s+ٱلرَّحِيمِ\s*/;

  const index = [];
  let total = 0;
  let stripped = 0;
  let problems = 0;

  for (let i = 1; i <= suras.length; i++) {
    const meta = suras[i - 1];
    const ayasCount = meta.ayas;
    const ayahs = [];

    if (i === 1) {
      // Surah Al-Fatihah with Bismillah above as header
      const raw7 = ar.get('1,7');
      const splitIdx = raw7.indexOf('غَيْرِ');
      const ar6 = raw7.slice(0, splitIdx).trim();
      const ar7 = raw7.slice(splitIdx).trim();

      ayahs.push({ n: 1, ar: ar.get('1,2'), tr: tr.get('1,2') });
      ayahs.push({ n: 2, ar: ar.get('1,3'), tr: tr.get('1,3') });
      ayahs.push({ n: 3, ar: ar.get('1,4'), tr: tr.get('1,4') });
      ayahs.push({ n: 4, ar: ar.get('1,5'), tr: tr.get('1,5') });
      ayahs.push({ n: 5, ar: ar.get('1,6'), tr: tr.get('1,6') });
      ayahs.push({ n: 6, ar: ar6, tr: 'The path of those upon whom You have bestowed favor,' });
      ayahs.push({ n: 7, ar: ar7, tr: 'not of those who have evoked [Your] anger or of those who are astray.' });
      stripped++;
    } else {
      for (let a = 1; a <= ayasCount; a++) {
        const key = `${i},${a}`;
        if (!ar.has(key) || !tr.has(key)) {
          console.error(`MISSING: surah ${i} ayah ${a}`);
          problems++;
          continue;
        }
        let text = ar.get(key);
        const translation = tr.get(key);

        if (a === 1 && i !== 9) {
          if (bismillahRegex.test(text)) {
            text = text.replace(bismillahRegex, '').trim();
            stripped++;
          } else {
            console.error(`Surah ${i} Ayah 1 does not match Bismillah prefix: ${text.slice(0, 30)}`);
            problems++;
          }
        }

        if (!text || !translation) {
          console.error(`EMPTY: surah ${i} ayah ${a}`);
          problems++;
        }

        ayahs.push({ n: a, ar: text, tr: translation });
      }
    }

    const header = i !== 9;
    const surahFileName = `surah_${String(i).padStart(3, '0')}.json`;
    fs.writeFileSync(
      path.join(outDir, surahFileName),
      JSON.stringify({ number: i, bismillahHeader: header, ayahs }, null, 0),
      'utf-8'
    );

    index.push({
      number: i,
      nameArabic: meta.name_ar,
      nameEnglish: meta.name_en,
      nameTransliteration: meta.name_tr,
      ayahCount: ayasCount,
      type: meta.typ.toLowerCase().startsWith('mec') ? 'Makki' : 'Madani',
      bismillahHeader: header,
    });

    total += ayahs.length;
  }

  fs.writeFileSync(
    path.join(outDir, 'surahs.json'),
    JSON.stringify(index, null, 2),
    'utf-8'
  );

  const lines = [
    '// GENERATED by tools/convert_quran.js — do not edit by hand',
    "import type { SurahContent } from '../../types/quran';",
    '',
    'export const surahLoaders: Record<number, () => SurahContent> = {'
  ];
  for (let i = 1; i <= 114; i++) {
    const padded = String(i).padStart(3, '0');
    lines.push(`  ${i}: () => require('./surah_${padded}.json') as SurahContent,`);
  }
  lines.push('};');
  lines.push('');

  fs.writeFileSync(
    path.join(outDir, 'index.ts'),
    lines.join('\n'),
    'utf-8'
  );

  console.log(`Surahs: ${index.length} | Total ayahs: ${total} (expected 6236) | Bismillah moved from ayah 1: ${stripped} (expected 0 or 112) | problems: ${problems}`);

  if (total !== 6236 || problems > 0) {
    console.error('WARNING: validation failed — do NOT use this data until fixed.');
    process.exit(1);
  }
  console.log('SUCCESS: All 114 Surahs generated and validated successfully!');
}

main();

